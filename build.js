// Directory where your JS files are
const jsDir = path.join(__dirname, 'js');
// Output file
const outputFile = path.join(__dirname, 'js', 'bundle.js');

// Read and combine all files
let combinedCode = '// BUNDLED FILE - Generated by build.js\n\n';

jsFiles.forEach((file) => {
  const filePath = path.join(jsDir, file);
  try {
    if (fs.existsSync(filePath)) {
      const content = fs.readFileSync(filePath, 'utf8');
      combinedCode += `// ===== ${file} =====\n`;
      combinedCode += content + '\n\n';
      console.log(`✅ Added: ${file}`);
    } else {
      console.log(`⚠️  Warning: ${file} not found, skipping...`);
    }
  } catch (err) {
    console.log(`❌ Error reading ${file}: ${err.message}`);
  }
});

// Write the combined file
fs.writeFileSync(outputFile, combinedCode, 'utf8');
console.log(`\n✅ Bundle created: ${outputFile}`);
