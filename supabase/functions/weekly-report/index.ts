serve(async (req)=>{
  if (req.method === "OPTIONS") {
    return new Response("ok", {
      headers: corsHeaders
    });
  }
  try {
    console.log("🚀 Starting Weekly Report Generator...");
    const supabase = createClient(Deno.env.get("SUPABASE_URL") ?? "", Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "");
    const now = new Date();
    const sevenDaysAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
    const sevenDaysAgoStr = sevenDaysAgo.toISOString().split("T")[0];
    console.log(`📊 Weekly report: ${sevenDaysAgoStr} to ${now.toISOString().split("T")[0]}`);
    // ============================================
    // 🔍 Get ALL active businesses
    // ============================================
    console.log("🔍 Fetching active businesses...");
    const { data: businesses, error: bizError } = await supabase.from("business_info").select("id, name, email, currency, logo_url, license_plan, language").not("email", "is", null).neq("email", "").or("license_status.eq.active,license_status.eq.trial,license_status.eq.trialing");
    if (bizError) {
      console.error("❌ Error fetching businesses:", bizError);
      throw bizError;
    }
    // Filter for Professional and Enterprise only
    let allBusinesses = (businesses || []).filter((biz)=>{
      const plan = (biz.license_plan || '').toLowerCase();
      return plan.includes('professional') || plan.includes('enterprise') || plan.includes('business') || plan === 'pro' || plan === 'premium';
    });
    const totalBusinesses = allBusinesses.length || 0;
    console.log(`📊 Found ${totalBusinesses} businesses to process`);
    if (totalBusinesses > 0) {
      const plans = allBusinesses.map((b)=>`${b.name}: ${b.license_plan} (${b.language || 'en'})`).join(', ');
      console.log(`📋 Plans found: ${plans}`);
    }
    const results = [];
    let totalEmailsSent = 0;
    let totalErrors = 0;
    for(let i = 0; i < allBusinesses.length; i++){
      const biz = allBusinesses[i];
      console.log(`\n${"=".repeat(50)}`);
      console.log(`🔄 [${i + 1}/${totalBusinesses}] Processing: ${biz.name} (${biz.license_plan})`);
      console.log(`${"=".repeat(50)}`);
      try {
        const language = biz.language || 'en';
        const t = weeklyTranslations[language] || weeklyTranslations.en;
        const isEnterprise = biz.license_plan?.toLowerCase() === 'enterprise';
        console.log(`  🌍 Language: ${language} ${isEnterprise ? '🏢 ENTERPRISE' : ''}`);
        // ============================================
        // 📧 Get admins
        // ============================================
        console.log(`  📧 Fetching admins...`);
        const { data: admins, error: adminsError } = await supabase.from("users").select("email, username, full_name").eq("role", "administrator").eq("business_id", biz.id).not("email", "is", null).neq("email", "");
        if (adminsError) {
          console.error(`  ❌ Error fetching admins:`, adminsError);
        }
        if (!admins || admins.length === 0) {
          console.log(`  ⚠️ No admins found - skipping`);
          results.push({
            business: biz.name,
            status: "skipped",
            reason: "no admins"
          });
          continue;
        }
        console.log(`  ✅ Found ${admins.length} admin(s)`);
        // ============================================
        // 📦 Get stock
        // ============================================
        console.log(`  📦 Fetching stock items...`);
        const { data: stock, error: stockError } = await supabase.from("stock").select("*").eq("business_id", biz.id);
        if (stockError) {
          console.error(`  ❌ Error fetching stock:`, stockError);
        }
        const stockItems = stock || [];
        const lowStock = stockItems.filter((i)=>i.quantity < 3 && i.quantity > 0);
        const outOfStock = stockItems.filter((i)=>i.quantity === 0);
        const unsold = stockItems.filter((i)=>i.hasbeensold === false);
        console.log(`  📊 Stock: ${stockItems.length} total, ${lowStock.length} low, ${outOfStock.length} out, ${unsold.length} unsold`);
        // ============================================
        // 💰 Get sales
        // ============================================
        console.log(`  💰 Fetching sales data (last 7 days)...`);
        const { data: sales, error: salesError } = await supabase.from("sales").select("*").eq("business_id", biz.id).gte("date_sold", sevenDaysAgoStr);
        if (salesError) {
          console.error(`  ❌ Error fetching sales:`, salesError);
        }
        const weekSales = sales || [];
        const totalRevenue = weekSales.reduce((sum, s)=>{
          const amount = Number(s.total_amount) || Number(s.totalamount) || Number(s.price) || Number(s.unit_price) || 0;
          return sum + amount;
        }, 0);
        const totalTransactions = weekSales.length;
        console.log(`  💵 Revenue: ${totalRevenue}, Transactions: ${totalTransactions}`);
        // ============================================
        // 📧 Generate email
        // ============================================
        const emailHtml = generateWeeklyReportHTML({
          businessName: biz.name,
          logoUrl: biz.logo_url,
          language: language,
          currency: biz.currency || "XAF",
          sevenDaysAgo: sevenDaysAgo,
          now: now,
          totalTransactions: totalTransactions,
          totalRevenue: totalRevenue,
          stockItems: stockItems,
          lowStock: lowStock,
          outOfStock: outOfStock,
          unsold: unsold,
          plan: biz.license_plan || 'professional',
          weekSales: weekSales
        });
        // ============================================
        // 📨 Send emails
        // ============================================
        console.log(`  📨 Sending ${isEnterprise ? '🏢 ENTERPRISE' : ''} weekly reports to ${admins.length} admin(s)...`);
        const RESEND_KEY = Deno.env.get("RESEND_API_KEY") || "";
        let emailsSentForBusiness = 0;
        const subject = isEnterprise ? `🏢 ${t.subject} – ${biz.name}` : `${t.subject} – ${biz.name}`;
        for (const admin of admins || []){
          try {
            const res = await fetch("https://api.resend.com/emails", {
              method: "POST",
              headers: {
                "Content-Type": "application/json",
                "Authorization": `Bearer ${RESEND_KEY}`
              },
              body: JSON.stringify({
                from: "StockApp* Reports <support@stocksalesapp.store>",
                to: [
                  admin.email
                ],
                subject: subject,
                html: emailHtml
              })
            });
            const resData = await res.json();
            if (res.ok) {
              console.log(`     ✅ Email sent to ${admin.email} (${language})`);
              emailsSentForBusiness++;
              totalEmailsSent++;
            } else {
              console.error(`     ❌ Failed: ${admin.email}`, resData);
              totalErrors++;
            }
          } catch (e) {
            console.error(`     ❌ Error: ${admin.email}`, e);
            totalErrors++;
          }
        }
        console.log(`  ✅ Completed: ${emailsSentForBusiness}/${admins.length} emails sent`);
        results.push({
          business: biz.name,
          businessId: biz.id,
          plan: biz.license_plan,
          language: language,
          isEnterprise: isEnterprise,
          adminsFound: admins.length,
          emailsSent: emailsSentForBusiness,
          totalRevenue,
          totalTransactions,
          stockCount: stockItems.length,
          lowStockCount: lowStock.length,
          outOfStockCount: outOfStock.length,
          unsoldCount: unsold.length
        });
      } catch (bizErr) {
        console.error(`  ❌ ERROR for ${biz.name}:`, bizErr);
        totalErrors++;
        results.push({
          business: biz.name,
          error: bizErr.message
        });
      }
    }
    // ============================================
    // 📊 Final summary
    // ============================================
    console.log("\n" + "=".repeat(50));
    console.log("📊 WEEKLY REPORT - SUMMARY");
    console.log("=".repeat(50));
    console.log(`✅ Emails sent: ${totalEmailsSent}`);
    console.log(`❌ Errors: ${totalErrors}`);
    console.log(`📋 Businesses processed: ${totalBusinesses}`);
    return new Response(JSON.stringify({
      success: true,
      results,
      summary: {
        totalEmailsSent,
        totalErrors,
        totalBusinessesProcessed: totalBusinesses
      }
    }, null, 2), {
      headers: {
        ...corsHeaders,
        "Content-Type": "application/json"
      }
    });
  } catch (error) {
    console.error("💥 FATAL ERROR:", error);
    return new Response(JSON.stringify({
      error: error.message
    }), {
      headers: {
        ...corsHeaders,
        "Content-Type": "application/json"
      },
      status: 500
    });
  }
});
